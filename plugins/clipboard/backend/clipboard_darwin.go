import "C"
import (
	"errors"
	"unsafe"
)

func readClipboard(previous uint64) (content, uint64, error) {
	sequence := uint64(C.clipSequence())
	if sequence == previous {
		return content{}, sequence, nil
	}
	var kind C.int
	var size C.size_t
	data := C.clipRead(&kind, &size)
	if data == nil {
		return content{}, sequence, nil
	}
	defer C.free(data)
	if uint64(C.clipSequence()) != sequence {
		return content{}, previous, nil
	}
	name := "text"
	if kind == 2 {
		name = "image"
	}
	return content{name, C.GoBytes(data, C.int(size))}, sequence, nil
}
func writeClipboard(c content) error {
	kind := 1
	if c.Kind == "image" {
		kind = 2
	}
	if len(c.Data) == 0 {
		return errors.New("empty clipboard")
	}
	if !bool(C.clipWrite(C.int(kind), unsafe.Pointer(&c.Data[0]), C.size_t(len(c.Data)))) {
		return errors.New("clipboard unavailable")
	}
	return nil
}
