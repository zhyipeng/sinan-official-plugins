// Start tests/serve.mjs, then pipe this script to ego-browser nodejs.
const task=await taskSpace('Sinan JSON plugin UI validation');
console.log({taskSpaceId:task.spaceId});
const page=task.page('p1');
await page.goto('http://127.0.0.1:9246');
await page.waitForFunction(()=>!document.querySelector('#editor').disabled);
await page.cdp('Emulation.setDeviceMetricsOverride',{width:680,height:480,deviceScaleFactor:1,mobile:false});
await page.fill('textarea[aria-label="JSON 内容"]','{"project":"Sinan","enabled":true,"tools":["JSON","搜索"]}');
await page.click('loc=role:button[name="格式化"]');
await page.waitForFunction(()=>document.querySelector('#editor').value.includes('\n')&&document.querySelector('#status').textContent==='草稿已保存');
await page.click('#editor');
await page.keyboard.press('Meta+Shift+Enter');
await page.waitForFunction(()=>!document.querySelector('#editor').value.includes('\n')&&document.querySelector('#status').textContent==='草稿已保存');
await page.fill('#editor','{broken');
await page.keyboard.press('Meta+Enter');
await page.waitForFunction(()=>!document.querySelector('#error').hidden);
if(await page.evaluate(()=>document.querySelector('#editor').value)!=='{broken')throw Error('invalid input discarded');
await page.waitForFunction(()=>document.querySelector('#status').textContent==='草稿已保存');
await page.evaluate(()=>{window.failSave=true;});
await page.fill('#editor','{"conflict":"keep this draft"}');
await page.waitForFunction(()=>document.querySelector('#status').textContent==='草稿未保存'&&!document.querySelector('#reload').hidden&&!document.querySelector('#error').hidden);
if(await page.evaluate(()=>document.querySelector('#editor').value)!=='{"conflict":"keep this draft"}')throw Error('save failure lost draft');
await page.evaluate(()=>{window.failSave=false;});
await page.click('loc=role:button[name="载入已存草稿"]');
await page.waitForFunction(()=>document.querySelector('#editor').value==='{broken'&&!document.querySelector('#editor').disabled);
await page.click('loc=role:button[name="清空"]');
await page.waitForFunction(()=>document.querySelector('#editor').value===''&&document.querySelector('#status').textContent==='草稿已保存');
await page.fill('#editor','{"project":"Sinan","enabled":true,"tools":["JSON","搜索"],"options":{"indent":2,"saveDraft":true}}');
await page.click('loc=role:button[name="格式化"]');
await page.waitForFunction(()=>document.querySelector('#editor').value.includes('\n')&&document.querySelector('#status').textContent==='草稿已保存');
console.log({screenshot:await page.screenshot({path:'/tmp/sinan-json-editor.png'})});
await page.cdp('Emulation.setDeviceMetricsOverride',{width:360,height:480,deviceScaleFactor:1,mobile:false});
if(await page.evaluate(()=>document.documentElement.scrollWidth>360))throw Error('narrow viewport overflows');
console.log('PASS: format, compact, keyboard, invalid input retention, save failure, explicit restore, clear and narrow layout');
console.log(await page.snapshot());
await task.finish({keep:[]});
